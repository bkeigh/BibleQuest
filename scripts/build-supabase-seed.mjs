/**
 * Emit supabase/seed.sql from the same verified content the app ships with.
 * Run after 0001_init.sql + policies.sql. Idempotent (on conflict do nothing).
 *
 *   node scripts/build-supabase-seed.mjs <seed-result.json>
 */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const src = process.argv[2];
if (!src) {
  console.error("Usage: node scripts/build-supabase-seed.mjs <seed-result.json>");
  process.exit(1);
}
const data = JSON.parse(readFileSync(src, "utf8"));
const daily = JSON.parse(
  readFileSync(path.join(process.cwd(), "src/data/seed/daily-verses.json"), "utf8")
);

const q = (v) => {
  if (v === null || v === undefined) return "null";
  if (typeof v === "number") return String(v);
  if (typeof v === "boolean") return v ? "true" : "false";
  return `'${String(v).replace(/'/g, "''")}'`;
};
const arr = (a) =>
  a && a.length
    ? `array[${a.map((x) => q(x)).join(", ")}]::text[]`
    : `'{}'::text[]`;

let out = `-- BibleQuest seed data — AUTO-GENERATED by scripts/build-supabase-seed.mjs
-- Content verified by the biblequest-seed-content workflow.
-- Scripture: World English Bible (public domain). Run after policies.sql.

begin;

-- Faith provider
insert into faith_providers (key, name, description, canonical_text_label)
values ('christianity', 'BibleQuest', 'A peaceful Christian spiritual companion.', 'Bible')
on conflict (key) do nothing;

-- Translation metadata (public domain)
insert into bible_translations (faith_provider_id, key, name, abbreviation, copyright_status, license_notes, is_default, is_active)
select id, 'web', 'World English Bible', 'WEB', 'public_domain', 'Public Domain. No license required.', true, true
from faith_providers where key = 'christianity'
on conflict (key) do nothing;

-- Feature flags (all Plus features off in V1)
insert into feature_flags (key, description, enabled) values
  ('ai_guide', 'Gentle AI study companion', false),
  ('personalized_quests', 'Personalized quest generation', false),
  ('advanced_reading_plans', 'Guided reading plans', false),
  ('premium_themes', 'Premium seasonal themes', false),
  ('voice_journaling', 'Voice journaling', false),
  ('reflection_insights', 'Reflection insights over time', false),
  ('year_in_review', 'Year in Review', false),
  ('family_groups', 'Family prayer circles', false)
on conflict (key) do nothing;

`;

// Milestones
out += "-- Milestones\ninsert into milestones (key, title, description, milestone_type, requirement_metric, requirement_count, icon_key) values\n";
out += data.milestones
  .map(
    (m) =>
      `  (${q(m.key)}, ${q(m.title)}, ${q(m.description)}, ${q(m.milestone_type)}, ${q(m.requirement_metric)}, ${m.requirement_count}, ${q(m.icon_key)})`
  )
  .join(",\n");
out += "\non conflict (key) do nothing;\n\n";

// Prayer prompts
out += "-- Prayer prompts\ninsert into prayer_prompts (key, text, category) values\n";
out += data.prayerPrompts
  .map((p) => `  (${q(p.id)}, ${q(p.text)}, ${q(p.category)})`)
  .join(",\n");
out += "\non conflict (key) do nothing;\n\n";

// Reflection prompts
out += "-- Reflection prompts\ninsert into reflection_prompts (key, text, context) values\n";
out += data.reflectionPrompts
  .map((p) => `  (${q(p.id)}, ${q(p.text)}, ${q(p.context)})`)
  .join(",\n");
out += "\non conflict (key) do nothing;\n\n";

// Daily verses
out += "-- Daily verse pool\ninsert into daily_verses (reference, book_slug, chapter, verse_start, verse_end, text, theme) values\n";
out += daily
  .map(
    (d) =>
      `  (${q(d.reference)}, ${q(d.bookSlug)}, ${d.chapter}, ${d.verseStart}, ${d.verseEnd}, ${q(d.text)}, ${q(d.theme)})`
  )
  .join(",\n");
out += "\non conflict do nothing;\n\n";

// Quests — reference the christianity provider id
out += "-- Quest templates\n";
out += "insert into quest_templates (faith_provider_id, slug, title, category, duration_minutes, difficulty, energy_level, solo_or_social, indoor_or_outdoor, invitation, why_it_matters, scripture_reference, scripture_text_snapshot, reflection_prompt, prayer_prompt, growth_type, tags, season_tags, tradition_tags, sensitivity_tags, is_premium)\nselect fp.id, v.slug, v.title, v.category, v.duration_minutes, v.difficulty, v.energy_level, v.solo_or_social, v.indoor_or_outdoor, v.invitation, v.why_it_matters, v.scripture_reference, v.scripture_text_snapshot, v.reflection_prompt, v.prayer_prompt, v.growth_type, v.tags, v.season_tags, v.tradition_tags, v.sensitivity_tags, v.is_premium\nfrom faith_providers fp, (values\n";
out += data.quests
  .map((qt) => {
    const snapshot = qt.scriptureText ?? null;
    return `  (${q(qt.slug)}, ${q(qt.title)}, ${q(qt.category)}, ${qt.duration_minutes}, ${q(qt.difficulty)}, ${q(qt.energy_level)}, ${q(qt.solo_or_social)}, ${q(qt.indoor_or_outdoor)}, ${q(qt.invitation)}, ${q(qt.why_it_matters)}, ${q(qt.scripture_reference)}, ${q(snapshot)}, ${q(qt.reflection_prompt)}, ${q(qt.prayer_prompt)}, ${q(qt.growth_type)}, ${arr(qt.tags)}, ${arr(qt.season_tags)}, ${arr(qt.tradition_tags)}, ${arr(qt.sensitivity_tags)}, ${q(qt.is_premium)})`;
  })
  .join(",\n");
out +=
  "\n) as v(slug, title, category, duration_minutes, difficulty, energy_level, solo_or_social, indoor_or_outdoor, invitation, why_it_matters, scripture_reference, scripture_text_snapshot, reflection_prompt, prayer_prompt, growth_type, tags, season_tags, tradition_tags, sensitivity_tags, is_premium)\nwhere fp.key = 'christianity'\non conflict (slug) do nothing;\n\n";

out += "commit;\n";

writeFileSync(path.join(process.cwd(), "supabase/seed.sql"), out);
console.log(
  `Wrote supabase/seed.sql — ${data.quests.length} quests, ${data.prayerPrompts.length} prayer + ${data.reflectionPrompts.length} reflection prompts, ${data.milestones.length} milestones, ${daily.length} daily verses.`
);
